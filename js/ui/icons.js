const iconPalette = { '#': '#1a120b', '*': '#ffe6a8', '+': 'currentColor', o: '#a26531' };
const iconCache = Object.create(null);

function iconSvg(key) {
  const art = ICON_PIXELS[key];
  if (!art) return '';
  if (!iconCache[key]) {
    const grid = key === 'pause' || key === 'play' ? 12 : 16;
    const rows = art.trim().split(/\s+/);
    const top = Math.floor((grid - rows.length) / 2);
    const rects = rows.map((row, y) => {
      const runs = /([#*+o])\1*/g;
      let markup = '';
      for (let run = runs.exec(row); run; run = runs.exec(row)) {
        markup += `<rect x="${run.index}" y="${top + y}" width="${run[0].length}" height="1" fill="${iconPalette[run[1]]}"/>`;
      }
      return markup;
    }).join('');
    iconCache[key] = `<svg viewBox="0 0 ${grid} ${grid}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
  }
  return iconCache[key];
}

$('btnPause').innerHTML = iconSvg('pause');

