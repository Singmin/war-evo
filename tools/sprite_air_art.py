"""空军的原生像素画法。翅膀、操纵面和推进装置各有独立的逐帧姿势。"""
from PIL import Image, ImageDraw, ImageFilter
from contextlib import contextmanager
from math import cos, radians, sin

W,H = 74,58
teams = (
    ('#af6326', '#ffb338', '#ffe18c'),
    ('#6244a1', '#a875ec', '#dcbcff'),
)

class Pixel:
    def __init__(self, side, ink):
        self.im = Image.new('RGBA', (W + 20, H + 20))
        self.d = ImageDraw.Draw(self.im)
        self.ink = ink
        self.low,self.team,self.high = teams[side]
        self.project = lambda x, y: (x + 10, y + 10)

    @contextmanager
    def part(self, x, y, angle=0, dx=0, dy=0, sy=1):
        """改变部件相对于铰点的姿势，按新坐标在整数像素格上重画。"""
        prev = self.project
        c, s = cos(radians(angle)), sin(radians(angle))

        def project(px, py):
            lx, ly = px - x, (py - y) * sy
            return prev(round(x + lx*c - ly*s + dx), round(y + lx*s + ly*c + dy))

        self.project = project
        try:
            yield
        finally:
            self.project = prev

    def box(self, x0, y0, x1, y1):
        corners = [self.project(x,y) for x,y in ((x0,y0),(x1,y0),(x1,y1),(x0,y1))]
        xs, ys = zip(*corners)
        return (min(xs),min(ys),max(xs),max(ys))

    def p(self,c,*pts):
        self.d.polygon([self.project(*point) for point in pts],fill=c)

    def l(self,c,*pts,w=1):
        self.d.line([self.project(*point) for point in pts],fill=c,width=w)

    def r(self,c,x0,y0,x1,y1):
        self.d.rectangle(self.box(x0,y0,x1,y1),fill=c)

    def e(self,c,x0,y0,x1,y1):
        self.d.ellipse(self.box(x0,y0,x1,y1),fill=c)

    def dot(self,c,x,y):
        self.d.point(self.project(x,y),fill=c)

    def finish(self):
        alpha = self.im.getchannel('A')
        outline = Image.new('RGBA', self.im.size, self.ink)
        outline.putalpha(alpha.filter(ImageFilter.MaxFilter(3)))
        outline.alpha_composite(self.im)
        return outline



def propeller(a, x, y, phase, metal, light):
    """同一旋转轴的四个投影，正侧视交替露出桨叶。"""
    (x0, y0), (x1, y1) = (
        ((-1,-7),(1,7)), ((-2,-5),(2,5)),
        ((-2,-2),(2,2)), ((1,-6),(-1,6)),
    )[phase % 4]
    a.l(metal,(x+x0,y+y0),(x+x1,y+y1))
    a.dot(light,x+x0,y+y0)
    a.dot(light,x,y)


def fan(a, x, y, phase, metal, light):
    """涵道内的叶片旋转，中心轴在四帧中固定。"""
    dx, dy = ((5,0),(4,2),(1,3),(-4,2))[phase % 4]
    a.l(metal,(x-dx,y-dy),(x+dx,y+dy))
    a.dot(light,x,y)


