def eagle_trainer(side, pose):
    dim, flag, light = teams[side]
    img = Image.new('RGBA', (66, 49))
    d = ImageDraw.Draw(img)
    def poly(points, color): d.polygon(points, fill=color)
    def line(points, color, width=1): d.line(points, fill=color, width=width)
    def dot(x, y, color): d.point((x,y), fill=color)
    def rect(x0,y0,x1,y1,color): d.rectangle((x0,y0,x1,y1), fill=color)

    (far, far_lit), (near, near_lit, seams) = EAGLE_WINGS[pose.eagle]
    if pose.eagle == 'recover':
        near = [(x + (x < 16), y + (x < 27) * 2) for x, y in near]
        near_lit = [(x + (x < 16), y + (x < 27) * 2) for x, y in near_lit]
        seams = [((x + (x < 16), y + (x < 27) * 2), (x1, y1 + (x1 < 27) * 2))
                 for (x, y), (x1, y1) in seams]
    poly(far, dark)
    poly(far_lit, shade)
    # Fan tail and tucked feet
    poly([(25,23),(14,24),(7,24),(7,26),(10,27),(8,29),(12,29),(11,31),(19,31),(25,29)], shade)
    line([(9,26),(15,26),(21,25)], feather)
    line([(13,30),(20,28)], dark)
    line([(34,28),(36,33),(40,33)], dark, 2)
    line([(31,29),(33,34),(37,35)], ochre, 2)
    dot(39,33,cream)
    dot(37,35,bone)
